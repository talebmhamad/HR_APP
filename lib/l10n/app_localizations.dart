  String get rememberMe;

  /// No description provided for @forgotPassword.
  ///
  /// In en, this message translates to:
  /// **'Forgot password?'**
  String get forgotPassword;

  /// No description provided for @login.
  ///
  /// In en, this message translates to:
  /// **'Log in'**
  String get login;

  /// No description provided for @intracore.
  ///
  /// In en, this message translates to:
  /// **'IntraCore'**
  String get intracore;

  /// No description provided for @employeePortal.
  ///
  /// In en, this message translates to:
  /// **'EMPLOYEE PORTAL'**
  String get employeePortal;

  /// No description provided for @selectLanguage.
  ///
  /// In en, this message translates to:
  /// **'Select Language'**
  String get selectLanguage;

  /// No description provided for @menuHome.
  ///
  /// In en, this message translates to:
  /// **'Home'**
  String get menuHome;

  /// No description provided for @menuTimeClock.
  ///
  /// In en, this message translates to:
  /// **'Time Clock'**
  String get menuTimeClock;

  /// No description provided for @menuTimesheets.
  ///
  /// In en, this message translates to:
  /// **'Timesheets'**
  String get menuTimesheets;

  /// No description provided for @menuApprovals.
  ///
  /// In en, this message translates to:
  /// **'Approvals'**
  String get menuApprovals;

  /// No description provided for @menuMore.
  ///
  /// In en, this message translates to:
